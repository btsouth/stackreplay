import { writeFile } from "node:fs/promises";
import { decisionSnapshotHash } from "../dist/decision-snapshot.js";
import { compileExecutionPlan, selectExecutionVersionAt } from "../dist/execution-compiler.js";
import { loadDefaultCatalog } from "../dist/load.js";

const catalog = loadDefaultCatalog();
// Fixed end-of-day cutoff after the provider-dated September 29 DevDay release.
// This reviewed decision snapshot is independent of observation time and the viewer clock.
const rulesAt = "2026-09-29T23:59:59Z";
const reviewUntil = "2026-10-27T00:00:00Z";
const plans = Object.values(catalog.plans)
  .flatMap((plan) => {
    const version = selectExecutionVersionAt(plan.executionVersions ?? [], rulesAt);
    if (!version) return [];
    const overlays = (plan.executionOverlays ?? [])
      .filter((o) => o.id === "gpt-5-6-sol-promotion-d0")
      .map((o) => o.id);
    const artifact = compileExecutionPlan(catalog, plan.id, version.id, overlays, rulesAt).artifact;
    return [
      {
        id: plan.id,
        name: plan.name,
        provider: catalog.providers[plan.providerId]?.name ?? plan.providerId,
        providerId: plan.providerId,
        claims: version.claims,
        artifact,
      },
    ];
  })
  .sort((a, b) => a.id.localeCompare(b.id));
const scenarios = [
  { id: "cache-5m", label: "5-minute cache-write assumption", overlay: "cache-write-5m-d0" },
  { id: "cache-1h", label: "1-hour cache-write assumption", overlay: "cache-write-1h-d0" },
].map(({ id, label, overlay }) => ({
  id,
  label,
  assumption: `Counterfactual only: all undifferentiated Claude cache writes use ${id === "cache-5m" ? "five-minute" : "one-hour"} pricing. No source duration was observed. Assume standard direct API access, compatible request protocol and paid credentials; tokens only, excluding tools, tax and negotiated rates.`,
  artifacts: plans
    .filter((p) => p.artifact.purchase.kind === "api")
    .map((p) => {
      const plan = catalog.plans[p.id];
      const ids = [...p.artifact.appliedOverlayIds];
      if (plan.executionOverlays?.some((o) => o.id === overlay)) ids.push(overlay);
      return compileExecutionPlan(catalog, p.id, p.artifact.planVersionId, ids, rulesAt).artifact;
    }),
}));
// A snapshot refresh cannot extend an artifact or overlay's reviewed validity.
if (Date.parse(reviewUntil) <= Date.parse(rulesAt))
  throw new Error("Review horizon precedes snapshot");
for (const artifact of [
  ...plans.map((p) => p.artifact),
  ...scenarios.flatMap((s) => s.artifacts),
]) {
  if (Date.parse(reviewUntil) > Date.parse(artifact.validity.end))
    throw new Error(`Review horizon exceeds ${artifact.planId} artifact validity`);
}
await writeFile(
  new URL("../src/decision-market.generated.ts", import.meta.url),
  `/** GENERATED by scripts/build-decision-market.mjs; accepted catalog only. */\nimport type { DecisionMarket } from "./decision-market.js";\nexport const DECISION_MARKET: DecisionMarket = ${JSON.stringify({ rulesAt, reviewUntil, catalogHash: catalog.catalogVersion, decisionSnapshotHash: decisionSnapshotHash({ rulesAt, reviewUntil, scenarios, plans }), scenarios, plans }, null, 2)};\n`,
);
